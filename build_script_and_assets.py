def build_script():
    doc = Document()
    set_font(doc)
    sec = doc.sections[0]
    sec.top_margin = Cm(2.2)
    sec.bottom_margin = Cm(2.2)
    sec.left_margin = Cm(2.4)
    sec.right_margin = Cm(2.4)

    for item in SCRIPT:
        kind = item[0]
        if kind == "title":
            para(doc, item[1], size=26, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER,
                 before=40, after=6)
        elif kind == "sub":
            para(doc, item[1], size=13, color=GRAY, align=WD_ALIGN_PARAGRAPH.CENTER, after=4)
        elif kind == "meta":
            para(doc, item[1], size=9, color=GRAY, align=WD_ALIGN_PARAGRAPH.CENTER, after=2)
        elif kind == "h1":
            p = doc.add_paragraph(style="Heading 1")
            p.paragraph_format.space_before = Pt(18)
            p.paragraph_format.space_after = Pt(8)
            p.paragraph_format.keep_with_next = True
            set_run(p.add_run(item[1]), 15, bold=True, color=INK)
            # 去掉 Word 标题默认蓝色
            p.runs[0].font.color.rgb = RGBColor(*INK)
        elif kind == "p":
            para(doc, item[1], size=10.5, indent=0.0, after=5)
        elif kind == "q":
            para(doc, item[1], size=10, color=(70, 70, 70), indent=0.8, after=3)
        elif kind == "v":
            para(doc, item[1], size=10.5, italic=True, color=(60, 60, 60),
                 indent=1.4, after=2)
        elif kind == "c":
            para(doc, item[1], size=9.5, color=GRAY, indent=0.8, after=3)
        elif kind == "d":
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(1.0)
            p.paragraph_format.space_after = Pt(3)
            p.paragraph_format.line_spacing = 1.35
            set_run(p.add_run(item[1] + "："), 10.5, bold=True)
            set_run(p.add_run(item[2]), 10.5)
        elif kind == "tbl":
            table(doc, item[1], item[2], item[3], size=9)
            para(doc, "", size=4, after=2)

    doc.save(OUT_SCRIPT)
    print("saved:", OUT_SCRIPT)


