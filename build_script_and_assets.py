def para(doc, text="", size=10.5, bold=False, italic=False, color=None,
         indent=0.0, align=None, before=0, after=4, spacing=1.35):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(indent)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.line_spacing = spacing
    if align is not None:
        p.alignment = align
    if text:
        set_run(p.add_run(text), size, bold, italic, color)
    return p


def h1(doc, text, size=16, color=INK):
    p = para(doc, text, size=size, bold=True, color=color, before=16, after=8)
