def set_font(doc):
    st = doc.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(11)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")

def add(doc, text, style=None, bold=False, size=None, color=None, align=None):
    p = doc.add_paragraph(style=style)
    r = p.add_run(text)
    r.bold = bold
    if size: r.font.size = Pt(size)
    if color: r.font.color.rgb = RGBColor(*color)
    if align: p.alignment = align
    r.font.name = "Calibri"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
    return p

def h1(doc, t): add(doc, t, style="Heading 1")
def h2(doc, t): add(doc, t, style="Heading 2")
def body(doc, t): add(doc, t)
def bullet(doc, t): add(doc, t, style="List Bullet")
def quote(doc, t):
    p = add(doc, t)
    p.paragraph_format.left_indent = Cm(0.75)
    p.runs[0].italic = True

def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = "Table Grid"
    for j, x in enumerate(header):
        cell = t.rows[0].cells[j]
        cell.text = x
        for r in cell.paragraphs[0].runs:
            r.bold = True
    for i, row in enumerate(rows):
        for j, x in enumerate(row):
            t.rows[i + 1].cells[j].text = x
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Cm(w)
    return t

